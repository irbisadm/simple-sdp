// "strict reason -> lenient code -> action" for every way sdpReader.parse can reject a
// description (src/services/sdp-reader/ and assembly/reader/). Each entry is an input that
// strict mode rejects with exactly `reason` on `lineNumber`; for the same input the first
// lenient warning must carry the same line number and reason, plus `code` and `action`.
// Used by test/lenient.spec.ts and, through the adapter, by the wasm suite.
import type {SdpParseWarningAction, SdpParseWarningCode} from '../src';

export interface ReasonMapEntry {
  name: string;
  lines: string[];
  lineNumber: number;
  reason: string;
  code: SdpParseWarningCode;
  action: SdpParseWarningAction;
}

/** CRLF-terminated text of an entry; '' for no lines */
export const entryText = (entry: ReasonMapEntry): string =>
  entry.lines.length ? entry.lines.join('\r\n') + '\r\n' : '';

